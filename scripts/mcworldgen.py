#!/usr/bin/env python3
"""Build a Bedrock .mcworld from a building plan.

The bundled flat template already has cheats/command blocks enabled. A data
behavior pack adds one function that places the plan on the first tick, so the
world contains a real build as soon as it is opened. No AuroraBuild or Go
toolchain is required.

Plan format is the same as scripts/buildgen.py:
fills, blocks, commands.

Usage:
    python3 scripts/mcworldgen.py plan.json out.mcworld
"""
from __future__ import annotations
import argparse, json, uuid, zipfile
from pathlib import Path

TEMPLATE = Path(__file__).resolve().parent.parent / "assets" / "mcworld-template.mcworld"
MAX_FILL = 32768
PACK_NS = uuid.UUID("8f1f0c2e-6a7d-4a2a-9c4c-2f6b1e7d9a10")


def split_fill(a, b):
    lo = [min(a[i], b[i]) for i in range(3)]
    hi = [max(a[i], b[i]) for i in range(3)]
    # split along z so each fill <= 32768
    dx = hi[0] - lo[0] + 1
    dy = hi[1] - lo[1] + 1
    dz = hi[2] - lo[2] + 1
    step = max(1, MAX_FILL // max(1, dx * dy))
    z = lo[2]
    while z <= hi[2]:
        z2 = min(hi[2], z + step - 1)
        yield (*lo[:2], z, hi[0], hi[1], z2)
        z = z2 + 1


def plan_commands(plan):
    out = []
    for f in plan.get("fills", []):
        a, b, block = list(map(int, f["from"])), list(map(int, f["to"])), f["block"]
        states = f.get("states", "")
        suffix = f" {states}" if states else ""
        for x1, y1, z1, x2, y2, z2 in split_fill(a, b):
            out.append(f"fill {x1} {y1} {z1} {x2} {y2} {z2} {block}{suffix}")
    for b in plan.get("blocks", []):
        x, y, z = map(int, b["pos"])
        states = b.get("states", "")
        suffix = f" {states}" if states else ""
        out.append(f"setblock {x} {y} {z} {b['block']}{suffix}")
    out.extend(c["command"] for c in plan.get("commands", []))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("plan")
    ap.add_argument("out")
    args = ap.parse_args()
    plan = json.load(open(args.plan, encoding="utf-8"))
    name = plan.get("name", "Build")
    commands = plan_commands(plan)
    pack_id = str(uuid.uuid5(PACK_NS, name))
    module_id = str(uuid.uuid5(PACK_NS, name + ":data"))

    manifest = {
        "format_version": 2,
        "header": {
            "name": f"{name} Builder",
            "description": "Generated by mcbe-command-blocks/mcworldgen.py",
            "uuid": pack_id,
            "version": [1, 0, 0],
            "min_engine_version": [1, 21, 0],
        },
        "modules": [{
            "type": "data", "uuid": module_id, "version": [1, 0, 0],
        }],
    }
    tick = "\n".join([
        "scoreboard objectives add build_done dummy",
        "execute if score build_done all matches 0 run function build/place",
        "scoreboard players set build_done all 1",
    ]) + "\n"
    place = "\n".join(commands) + "\n"

    with zipfile.ZipFile(TEMPLATE, "r") as src, zipfile.ZipFile(args.out, "w", zipfile.ZIP_DEFLATED) as dst:
        for info in src.infolist():
            data = src.read(info.filename)
            if info.filename == "levelname.txt":
                data = (name + "\n").encode("utf-8")
            dst.writestr(info, data)
        dst.writestr("behavior_packs/build/manifest.json", json.dumps(manifest, ensure_ascii=False, indent=2))
        dst.writestr("behavior_packs/build/functions/tick.json", json.dumps({"values": ["build/tick"]}))
        dst.writestr("behavior_packs/build/functions/build/tick.mcfunction", tick)
        dst.writestr("behavior_packs/build/functions/build/place.mcfunction", place)
        dst.writestr("world_behavior_packs.json", json.dumps([{
            "pack_id": pack_id, "version": [1, 0, 0]
        }], indent=2))
    print(json.dumps({"name": name, "out": args.out, "commands": len(commands),
                      "pack_id": pack_id, "bytes": Path(args.out).stat().st_size}, ensure_ascii=False))


if __name__ == "__main__":
    main()
